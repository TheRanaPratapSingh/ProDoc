using ProDoc.Application.Billing;
using ProDoc.Domain.Billing;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace ProDoc.Infrastructure.Billing;

public sealed class InvoicePdfGenerator : IInvoicePdfGenerator
{
    static InvoicePdfGenerator()
    {
        QuestPDF.Settings.License = LicenseType.Community;
    }

    public Task<byte[]> GenerateAsync(Invoice invoice, CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();
        var bytes = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Margin(40);
                page.Size(PageSizes.A4);
                page.Header().Column(column =>
                {
                    column.Item().Text("ProDoc").FontSize(22).SemiBold().FontColor(Color.FromHex("#0F766E"));
                    column.Item().Text(invoice.Kind.ToString()).FontSize(12).FontColor(Colors.Grey.Darken1);
                });
                page.Content().PaddingVertical(20).Column(column =>
                {
                    column.Spacing(8);
                    column.Item().Text($"Invoice {invoice.Number}").SemiBold().FontSize(14);
                    column.Item().Text($"Issued (UTC): {invoice.IssuedAtUtc:yyyy-MM-dd HH:mm}");
                    column.Item().Text($"Bill to: {invoice.BillToName}");
                    if (!string.IsNullOrWhiteSpace(invoice.BillToDetail))
                    {
                        column.Item().Text(invoice.BillToDetail);
                    }

                    column.Item().PaddingTop(10).Text(invoice.Description);
                    column.Item().Text($"Subtotal: {invoice.Currency} {invoice.Subtotal:0.00}");
                    column.Item().Text($"Tax ({invoice.TaxCodeSnapshot ?? "n/a"} @ {invoice.TaxRateSnapshot:0.##}%): {invoice.Currency} {invoice.TaxAmount:0.00}");
                    column.Item().Text($"Total: {invoice.Currency} {invoice.Total:0.00}").SemiBold();
                    column.Item().Text($"Amount paid: {invoice.Currency} {invoice.AmountPaid:0.00}");
                    column.Item().Text($"Outstanding: {invoice.Currency} {invoice.Outstanding:0.00}");
                    column.Item().PaddingTop(16).Text(
                        "Tax treatment is driven by configurable ProDoc tax rules. This document does not constitute a certified GST invoice assessment.");
                });
                page.Footer().AlignCenter().Text("Generated by ProDoc");
            });
        }).GeneratePdf();
        return Task.FromResult(bytes);
    }
}
