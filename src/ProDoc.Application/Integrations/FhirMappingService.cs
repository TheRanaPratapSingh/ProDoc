using System.Text.Json;
using ProDoc.Domain.Appointments;
using ProDoc.Domain.Clinical;
using ProDoc.Domain.Providers;

namespace ProDoc.Application.Integrations;

/// <summary>
/// Produces FHIR R4-compatible JSON structures for a supported subset of resources.
/// This is a mapping layer, not a claim of full FHIR server certification.
/// </summary>
public sealed class FhirMappingService
{
    public const string FhirVersion = "4.0.1";

    public FhirBundleExport BuildPatientBundle(
        Guid accountUserId,
        string? fullName,
        string? phoneE164,
        PatientMedicalRecord? record,
        IReadOnlyList<Appointment> appointments,
        Doctor? doctor,
        Clinic? clinic,
        Prescription? prescription)
    {
        var entries = new List<object>();
        var patientId = $"Patient/{accountUserId:N}";
        entries.Add(Entry(patientId, MapPatient(accountUserId, fullName, phoneE164, record)));

        if (doctor is not null)
        {
            entries.Add(Entry($"Practitioner/{doctor.Id:N}", MapPractitioner(doctor)));
        }

        if (clinic is not null)
        {
            entries.Add(Entry($"Organization/{clinic.Id:N}", MapOrganization(clinic)));
        }

        foreach (var appointment in appointments.Take(50))
        {
            entries.Add(Entry($"Appointment/{appointment.Id:N}", MapAppointment(appointment, patientId)));
            if (appointment.Status == AppointmentStatus.Completed)
            {
                entries.Add(Entry($"Encounter/{appointment.Id:N}", MapEncounter(appointment, patientId)));
            }
        }

        if (record is not null)
        {
            var index = 0;
            foreach (var condition in record.Conditions.Take(50))
            {
                entries.Add(Entry($"Condition/{condition.Id:N}", MapCondition(condition, patientId, index++)));
            }

            foreach (var medication in record.Medications.Take(50))
            {
                entries.Add(Entry($"MedicationRequest/med-{medication.Id:N}", MapMedicationRequestFromChart(medication, patientId)));
            }
        }

        if (prescription is not null)
        {
            var version = prescription.Versions.OrderByDescending(item => item.VersionNumber).FirstOrDefault();
            if (version is not null)
            {
                foreach (var item in version.Items)
                {
                    entries.Add(Entry($"MedicationRequest/{item.Id:N}", MapMedicationRequestFromPrescription(item, patientId, prescription.Id)));
                }

                if (!string.IsNullOrWhiteSpace(version.ClinicalObservations))
                {
                    entries.Add(Entry($"Observation/obs-{version.Id:N}", MapObservation(version, patientId)));
                }

                if (!string.IsNullOrWhiteSpace(version.Diagnosis))
                {
                    entries.Add(Entry($"DiagnosticReport/dx-{version.Id:N}", MapDiagnosticReport(version, patientId)));
                }
            }
        }

        return new FhirBundleExport(
            "Bundle",
            "collection",
            DateTimeOffset.UtcNow.ToString("O"),
            entries,
            $"FHIR R4 ({FhirVersion}) subset export generated by ProDoc. Not a certified FHIR server response.");
    }

    public bool TryValidateBundleShape(string json, out string? error)
    {
        try
        {
            using var document = JsonDocument.Parse(json);
            if (!document.RootElement.TryGetProperty("resourceType", out var type) || type.GetString() != "Bundle")
            {
                error = "resourceType must be Bundle.";
                return false;
            }

            if (!document.RootElement.TryGetProperty("entry", out var entry) || entry.ValueKind != JsonValueKind.Array)
            {
                error = "Bundle.entry array is required.";
                return false;
            }

            error = null;
            return true;
        }
        catch (JsonException)
        {
            error = "JSON is not valid.";
            return false;
        }
    }

    private static object Entry(string fullUrl, object resource) => new { fullUrl, resource };

    private static object MapPatient(Guid userId, string? fullName, string? phone, PatientMedicalRecord? record) =>
        new
        {
            resourceType = "Patient",
            id = userId.ToString("N"),
            meta = new { profile = new[] { "http://hl7.org/fhir/StructureDefinition/Patient" } },
            name = string.IsNullOrWhiteSpace(fullName) && record is null
                ? Array.Empty<object>()
                : new object[] { new { use = "official", text = fullName ?? record!.SubjectName } },
            telecom = string.IsNullOrWhiteSpace(phone)
                ? Array.Empty<object>()
                : new object[] { new { system = "phone", value = MaskPhone(phone) } },
            active = true
        };

    private static object MapPractitioner(Doctor doctor) =>
        new
        {
            resourceType = "Practitioner",
            id = doctor.Id.ToString("N"),
            name = new object[]
            {
                new
                {
                    use = "official",
                    text = string.IsNullOrWhiteSpace(doctor.DisplayName)
                        ? $"{doctor.FirstName} {doctor.LastName}".Trim()
                        : doctor.DisplayName
                }
            }
        };

    private static object MapOrganization(Clinic clinic) =>
        new
        {
            resourceType = "Organization",
            id = clinic.Id.ToString("N"),
            name = clinic.Name ?? clinic.Reference,
            active = true
        };

    private static object MapAppointment(Appointment appointment, string patientRef) =>
        new
        {
            resourceType = "Appointment",
            id = appointment.Id.ToString("N"),
            status = MapAppointmentStatus(appointment.Status),
            start = appointment.StartsAtUtc.ToString("O"),
            end = appointment.EndsAtUtc.ToString("O"),
            participant = new object[]
            {
                new { actor = new { reference = patientRef }, status = "accepted" },
                new { actor = new { reference = $"Practitioner/{appointment.DoctorId:N}" }, status = "accepted" }
            }
        };

    private static object MapEncounter(Appointment appointment, string patientRef) =>
        new Dictionary<string, object?>
        {
            ["resourceType"] = "Encounter",
            ["id"] = appointment.Id.ToString("N"),
            ["status"] = "finished",
            ["class"] = new { system = "http://terminology.hl7.org/CodeSystem/v3-ActCode", code = "AMB", display = "ambulatory" },
            ["subject"] = new { reference = patientRef },
            ["period"] = new { start = appointment.StartsAtUtc.ToString("O"), end = appointment.EndsAtUtc.ToString("O") },
            ["serviceProvider"] = new { reference = $"Organization/{appointment.ClinicId:N}" }
        };

    private static object MapCondition(PatientMedicalCondition condition, string patientRef, int _) =>
        new
        {
            resourceType = "Condition",
            id = condition.Id.ToString("N"),
            subject = new { reference = patientRef },
            code = new { text = condition.Name },
            clinicalStatus = new
            {
                coding = new object[]
                {
                    new
                    {
                        system = "http://terminology.hl7.org/CodeSystem/condition-clinical",
                        code = "active"
                    }
                }
            }
        };

    private static object MapMedicationRequestFromChart(PatientMedication medication, string patientRef) =>
        new
        {
            resourceType = "MedicationRequest",
            id = $"med-{medication.Id:N}",
            status = "active",
            intent = "order",
            medicationCodeableConcept = new { text = medication.Name },
            subject = new { reference = patientRef },
            dosageInstruction = new object[] { new { text = medication.Notes ?? $"{medication.Dosage}; {medication.Frequency}".Trim(' ', ';') } }
        };

    private static object MapMedicationRequestFromPrescription(PrescriptionItem item, string patientRef, Guid prescriptionId) =>
        new
        {
            resourceType = "MedicationRequest",
            id = item.Id.ToString("N"),
            status = "active",
            intent = "order",
            medicationCodeableConcept = new { text = item.MedicineName },
            subject = new { reference = patientRef },
            dosageInstruction = new object[]
            {
                new
                {
                    text = $"{item.Dosage}; {item.Frequency}; {item.Duration}; {item.Route}",
                    patientInstruction = item.Instructions
                }
            },
            basedOn = new object[] { new { reference = $"Prescription/{prescriptionId:N}" } }
        };

    private static object MapObservation(PrescriptionVersion version, string patientRef) =>
        new
        {
            resourceType = "Observation",
            id = $"obs-{version.Id:N}",
            status = "final",
            code = new { text = "Clinical observations" },
            subject = new { reference = patientRef },
            valueString = version.ClinicalObservations
        };

    private static object MapDiagnosticReport(PrescriptionVersion version, string patientRef) =>
        new
        {
            resourceType = "DiagnosticReport",
            id = $"dx-{version.Id:N}",
            status = "final",
            code = new { text = "Consultation diagnosis summary" },
            subject = new { reference = patientRef },
            conclusion = version.Diagnosis
        };

    private static string MapAppointmentStatus(AppointmentStatus status) =>
        status switch
        {
            AppointmentStatus.Held => "pending",
            AppointmentStatus.Requested => "pending",
            AppointmentStatus.Confirmed => "booked",
            AppointmentStatus.CheckedIn => "checked-in",
            AppointmentStatus.Completed => "fulfilled",
            AppointmentStatus.Cancelled => "cancelled",
            AppointmentStatus.Rejected => "cancelled",
            AppointmentStatus.Expired => "noshow",
            _ => "pending"
        };

    private static string MaskPhone(string phone)
    {
        var digits = new string(phone.Where(char.IsDigit).ToArray());
        if (digits.Length < 4)
        {
            return "****";
        }

        return $"******{digits[^4..]}";
    }
}
