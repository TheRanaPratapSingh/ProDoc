export function useCopy(): Copy {
  const accountLanguage = useSessionStore((state) => state.account?.preferredLanguage);
  const preference = useUiStore((state) => state.language);
  const language: Language = accountLanguage ?? preference;
  return copy[language];
}

export function useActiveLanguage(): Language {
  const accountLanguage = useSessionStore((state) => state.account?.preferredLanguage);
  const preference = useUiStore((state) => state.language);
  return accountLanguage ?? preference;
}
